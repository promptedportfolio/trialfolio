"""`scripts/schemas` writes one schema for each contract, and `--check` finds every kind of drift.

Traces to docs/contracts.md, schema generation and drift, and to `scripts/schemas --check` in
release 0.1.0's verification commands. `scripts/check` runs the check on the committed schemas;
these tests check the generator itself, in a temporary directory.
"""

import json
import shutil
import subprocess
import typing
from pathlib import Path

import pytest

from tests.support.git import outside_any_repository
from trialfolio.contracts import schema_files
from trialfolio.contracts.schema_files import (
    JSON_SCHEMA_DIALECT,
    SCHEMA_FILES,
    check,
    generate,
    main,
    write,
)


def test_each_schema_names_its_model_and_mode() -> None:
    for name, content in generate().items():
        schema = json.loads(content)
        assert schema["$schema"] == JSON_SCHEMA_DIALECT, name
        assert "Generated by scripts/schemas from trialfolio.contracts." in schema["$comment"]
        assert " mode." in schema["$comment"]


def test_a_versioned_contract_names_its_version() -> None:
    """One file for each contract and each schema version that has a reader."""
    for schema_file in SCHEMA_FILES:
        field = schema_file.model.model_fields.get("schema_version")
        if field is None:
            continue
        (version,) = typing.get_args(field.annotation)
        assert schema_file.name.endswith(f"-{version}.schema.json")


def test_check_passes_after_write(tmp_path: Path) -> None:
    write(tmp_path)

    assert check(tmp_path) == []


def test_check_lists_each_kind_of_drift(tmp_path: Path) -> None:
    write(tmp_path)
    first, second = SCHEMA_FILES[0].name, SCHEMA_FILES[1].name
    (tmp_path / first).write_text("{}\n")
    (tmp_path / second).unlink()
    (tmp_path / "hand-written.schema.json").write_text("{}\n")

    assert check(tmp_path) == [
        f"differs: {first}",
        f"missing: {second}",
        "extra: hand-written.schema.json",
    ]


def test_check_of_a_missing_directory_lists_every_schema(tmp_path: Path) -> None:
    assert check(tmp_path / "absent") == [f"missing: {file.name}" for file in SCHEMA_FILES]


def test_write_replaces_drifted_files(tmp_path: Path) -> None:
    (tmp_path / SCHEMA_FILES[0].name).write_text("{}\n")

    write(tmp_path)

    assert sorted(path.name for path in tmp_path.iterdir()) == sorted(generate())
    assert check(tmp_path) == []


@pytest.mark.parametrize("extra", ["notes.txt", "stale.schema.json"])
def test_write_refuses_unexpected_files_without_changing_anything(
    tmp_path: Path, extra: str, capsys: pytest.CaptureFixture[str]
) -> None:
    """Regression: --dir must never delete unrelated files or partially regenerate schemas."""
    before = {SCHEMA_FILES[0].name: b"{}\n", extra: b"keep me\n"}
    for name, content in before.items():
        (tmp_path / name).write_bytes(content)

    assert main(["--dir", str(tmp_path)]) == 1
    assert "aren't current schemas" in capsys.readouterr().err
    assert {path.name: path.read_bytes() for path in tmp_path.iterdir()} == before


def test_write_refuses_a_file_as_the_directory(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    """Regression: a mistaken --dir naming a file is refused, not a traceback."""
    target = tmp_path / "README.md"
    target.write_bytes(b"keep me\n")

    assert main(["--dir", str(target)]) == 1
    assert "isn't a directory" in capsys.readouterr().err
    assert target.read_bytes() == b"keep me\n"


def test_a_generation_error_isnt_reported_as_a_directory_problem(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    def broken() -> None:
        raise ValueError("a defect in a model")

    monkeypatch.setattr(schema_files, "generate", broken)

    with pytest.raises(ValueError, match="a defect in a model"):
        main(["--dir", str(tmp_path)])


ROOT = Path(__file__).resolve().parents[2]


@pytest.mark.skipif(shutil.which("sh") is None, reason="scripts/schemas is a POSIX shell script")
def test_script_runs_from_any_directory_and_reads_dir_from_there(tmp_path: Path) -> None:
    """Regression: the script finds the repository from its own location, outside any Git
    repository too, and a relative --dir is relative to the caller's directory."""
    write(tmp_path / "out")
    result = subprocess.run(
        ["sh", str(ROOT / "scripts" / "schemas"), "--check", "--dir", "out"],
        cwd=tmp_path,
        env=outside_any_repository()
        | {"UV_NO_SYNC": "true", "UV_OFFLINE": "true", "UV_NO_ENV_FILE": "true"},
        capture_output=True,
        text=True,
        check=False,
    )

    assert result.returncode == 0, result.stderr
    assert "schemas in out match the models" in result.stdout


def test_git_checkout_preserves_schema_bytes_with_autocrlf(tmp_path: Path) -> None:
    """Regression: a Windows-style Git checkout must pass the byte-for-byte drift check."""
    (tmp_path / ".gitattributes").write_bytes((ROOT / ".gitattributes").read_bytes())
    write(tmp_path / "schemas")
    checkout = tmp_path / "checkout"
    checkout.mkdir()
    for args in (
        ["init", "--quiet"],
        ["-c", "core.autocrlf=false", "add", ".gitattributes", "schemas"],
        ["-c", "core.autocrlf=true", "checkout-index", "--all", f"--prefix={checkout}/"],
    ):
        subprocess.run(
            ["git", *args],
            cwd=tmp_path,
            env=outside_any_repository(),
            check=True,
            capture_output=True,
        )

    assert check(checkout / "schemas") == []


def test_main_exits_1_on_drift_and_writes_nothing(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    assert main(["--check", "--dir", str(tmp_path)]) == 1

    assert list(tmp_path.iterdir()) == []
    assert "To fix it, run scripts/schemas to regenerate the schemas." in capsys.readouterr().err


def test_check_says_to_delete_an_extra_file_by_hand(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    """Regression: writing never deletes, so an extra file alone isn't sent to scripts/schemas."""
    write(tmp_path)
    (tmp_path / "plan-0.9.0.schema.json").write_text("{}\n")

    assert main(["--check", "--dir", str(tmp_path)]) == 1
    error = capsys.readouterr().err
    assert "To fix it, delete each extra entry you've checked is obsolete." in error
    assert "run scripts/schemas" not in error


def test_main_writes_then_checks_clean(tmp_path: Path) -> None:
    assert main(["--dir", str(tmp_path)]) == 0
    assert main(["--check", "--dir", str(tmp_path)]) == 0


def test_hidden_files_are_ignored(tmp_path: Path) -> None:
    """A Finder .DS_Store, for example, is neither drift nor removed."""
    write(tmp_path)
    (tmp_path / ".DS_Store").write_bytes(b"\0")

    assert check(tmp_path) == []
    write(tmp_path)
    assert (tmp_path / ".DS_Store").exists()


def test_a_subdirectory_is_extra_and_stops_writing(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    (tmp_path / "old").mkdir()

    assert check(tmp_path)[-1] == "extra: old/"
    assert main(["--dir", str(tmp_path)]) == 1
    assert [path.name for path in tmp_path.iterdir()] == ["old"]
    assert "holds directories: old" in capsys.readouterr().err
